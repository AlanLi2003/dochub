def build_toc(markdown_text):
    """从 Markdown 文本中提取标题生成目录 JSON"""
    toc = []
    for line in markdown_text.split('\n'):
        line = line.strip()
        if line.startswith('# '):
            toc.append({'level': 1, 'text': line[2:].strip(), 'id': ''})
        elif line.startswith('## '):
            toc.append({'level': 2, 'text': line[3:].strip(), 'id': ''})
        elif line.startswith('### '):
            toc.append({'level': 3, 'text': line[4:].strip(), 'id': ''})
    return json.dumps(toc, ensure_ascii=False)


